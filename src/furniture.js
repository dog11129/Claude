const cache = new Map();
function built(k, fn) {
  if (!cache.has(k)) {
    const r = fn(), [p, gl] = Array.isArray(r[0]) ? r : [r, []];
    cache.set(k, [merge(p), gl.length ? merge(gl) : null]);
  }
  return cache.get(k);
}
function instance([geo, glow], shadow) {
  const g = new THREE.Group(), m = new THREE.Mesh(geo, MAT);
  m.castShadow = shadow;
  m.receiveShadow = true;
  g.add(m);
  if (glow) g.add(new THREE.Mesh(glow, GLOW));
  return g;
}

